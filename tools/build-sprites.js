'use strict';
/* Regenerates src/sprites.js: for every Pokémon of src/data.js, the PokéAPI id of its sprite.
   The images themselves are NOT stored anywhere: the page loads them at runtime from the PokéAPI sprites repository.
   Usage: node tools/build-sprites.js [--cached]   (one request to pokeapi.co, cached in tools/.cache/pokeapi-list.json) */
const fs = require('fs'), path = require('path'), vm = require('vm');
const CACHE = path.join(__dirname, '.cache', 'pokeapi-list.json'), OUT = path.join(__dirname, '..', 'src', 'sprites.js');
const UA = 'EVSmith-sprite-map/1.0 (open-source hobby tool)';
(async () => {
  fs.mkdirSync(path.dirname(CACHE), { recursive: true });
  if (!fs.existsSync(CACHE)) {
    if (process.argv.includes('--cached')) throw new Error('no cached list');
    const r = await fetch('https://pokeapi.co/api/v2/pokemon?limit=3000', { headers: { 'User-Agent': UA } });
    if (!r.ok) throw new Error('HTTP ' + r.status);
    fs.writeFileSync(CACHE, JSON.stringify(await r.json()));
  }
  const names = {}; JSON.parse(fs.readFileSync(CACHE, 'utf8')).results.forEach(r => { names[r.name] = +r.url.replace(/\/$/, '').split('/').pop(); });
  const ctx = {}; ctx.globalThis = ctx; vm.createContext(ctx); vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'src', 'data.js'), 'utf8'), ctx);
  const dex = Object.keys(ctx.POKEDEX_CHAMPIONS);
  const slug = s => s.toLowerCase().replace(/[’'.:]/g, '').replace(/\s+/g, '-').replace(/-f$/, '-female').replace(/-m$/, '-male');
  const byPrefix = (p, suffix) => Object.keys(names).filter(k => k.startsWith(p + '-') && (!suffix || k.endsWith(suffix))).sort((a, b) => names[a] - names[b])[0];
  const ALIAS = { 'Maushold-Four': 'maushold-family-of-four', 'Maushold': 'maushold-family-of-three' }; /* Showdown names that PokéAPI spells differently */
  const find = n => {
    if (ALIAS[n] && names[ALIAS[n]]) return ALIAS[n];
    const m = /^Mega (.+?)( [XYZ])?$/.exec(n);
    if (m) { const b = slug(m[1]), x = m[2] ? '-' + m[2].trim().toLowerCase() : ''; return [b + '-mega' + x, byPrefix(b, '-mega' + x)].find(k => k && names[k]); }
    const s = slug(n);
    return [s, s + '-breed', s + '-plumage', byPrefix(s)].find(k => k && names[k]);
  };
  /* species id of a form: the shortest dash-separated prefix of its name that is a base species (ids below 10000) */
  const root = n => { const parts = slug(n.replace(/^Mega /, '')).split('-'); for (let i = 1; i <= parts.length; i++) { const k = parts.slice(0, i).join('-'); const id = names[k] && names[k] < 10000 ? names[k] : (byPrefix(k) && names[byPrefix(k)] < 10000 ? names[byPrefix(k)] : 0); if (id) return id; } return 0; };
  const ids = {}, base = {}, missing = [];
  dex.forEach(n => {
    const k = find(n);
    if (!k) { missing.push(n); const r = root(n); if (r) base[n] = r; return; }
    ids[n] = names[k];
    if (names[k] > 10000) { const r = root(n); if (r) base[n] = r; }
  });
  fs.writeFileSync(OUT, `/* GENERATED by tools/build-sprites.js: PokéAPI sprite ids (images are loaded at runtime from the PokéAPI sprites repository). */\nvar SPRITES=${JSON.stringify(ids)};\nvar SPRITE_BASE=${JSON.stringify(base)};\n`);
  console.log(`${Object.keys(ids).length}/${dex.length} Pokémon mapped; ${Object.keys(base).length} with a fallback species id`);
  if (missing.length) console.log('no exact sprite (fallback to base species where possible):', missing.map(n => n + (base[n] ? ' → #' + base[n] : ' (none)')).join(', '));
})().catch(e => { console.error('build-sprites failed:', e.message); process.exit(1); });
