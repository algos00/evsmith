'use strict';
/* Regenerates src/tdata.js (tournament usage, abilities, items, moves, natures) from MunchStats' public JSON
   (Limitless TCG online tournaments, Pokémon Champions VGC).
   Usage: node tools/update-meta.js [--top 60] [--format M-C] [--players 25] [--delay 10] [--cached] [--out src/tdata.js]
   - Waits at least 10 s between requests (MunchStats' robots.txt crawl-delay) and sends no personal data.
   - Raw answers are kept in tools/.cache/ so --cached rebuilds the file without any request.
   - Names that do not exist in the app's game data (src/data.js) are dropped and listed at the end. */
const fs = require('fs'), path = require('path'), vm = require('vm');
const arg = (n, d) => { const i = process.argv.indexOf('--' + n); return i < 0 ? d : (process.argv[i + 1] && !process.argv[i + 1].startsWith('--') ? process.argv[i + 1] : true); };
const TOP = +arg('top', 60), FORMAT = arg('format', 'M-C'), PLAYERS = String(arg('players', '25')), CACHED = !!arg('cached', false);
const DELAY = Math.max(10, +arg('delay', 10)) * 1000, OUT = path.resolve(arg('out', path.join(__dirname, '..', 'src', 'tdata.js')));
const BASE = 'https://www.munchstats.com/limitless/api/', CACHE = path.join(__dirname, '.cache');
const UA = 'EVSmith-meta-updater/1.0 (open-source hobby tool)';
fs.mkdirSync(CACHE, { recursive: true });

const ctx = { window: {} }; ctx.globalThis = ctx; vm.createContext(ctx);
vm.runInContext(fs.readFileSync(path.join(__dirname, '..', 'src', 'data.js'), 'utf8'), ctx);
const norm = s => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const DEX = ctx.POKEDEX_CHAMPIONS, MV = ctx.MOVES_CHAMPIONS, ABL = new Set(ctx.ABILITIES_CHAMPIONS), ITL = new Set(ctx.ITEMS_CHAMPIONS), NAT = ctx.NATURES;
const dexIndex = {}; Object.keys(DEX).forEach(n => { dexIndex[norm(n)] = n; });
const skipped = { pokemon: new Set(), ability: new Set(), item: new Set(), move: new Set() };

function dexName(apiName) {
  const m = /^(.+)-Mega(?:-([XYZ]))?$/.exec(apiName);
  const cand = m ? 'Mega ' + m[1] + (m[2] ? ' ' + m[2] : '') : apiName;
  return dexIndex[norm(cand)] || dexIndex[norm(apiName)] || null;
}
const sleep = ms => new Promise(r => setTimeout(r, ms));
let last = 0;
async function get(name) {
  const file = path.join(CACHE, `${FORMAT}_${PLAYERS}_${name ? norm(name) : '_list'}.json`);
  if (fs.existsSync(file) && (CACHED || Date.now() - fs.statSync(file).mtimeMs < 6 * 3600e3)) return JSON.parse(fs.readFileSync(file, 'utf8'));
  if (CACHED) throw new Error('no cached answer for ' + (name || 'list'));
  const wait = last + DELAY - Date.now(); if (wait > 0) await sleep(wait);
  const url = `${BASE}${encodeURIComponent(FORMAT)}/${encodeURIComponent(PLAYERS)}/${name ? encodeURIComponent(name) : ''}?cut=all`;
  last = Date.now();
  const res = await fetch(url, { headers: { 'User-Agent': UA, Accept: 'application/json' } });
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const j = await res.json(); fs.writeFileSync(file, JSON.stringify(j)); return j;
}
const pct = x => Math.round(parseFloat(x) * 10) / 10;
function pick(list, valid, kind, max) { /* [[name, "pct", ...]] -> {names, pc} keeping only names the app knows */
  const names = [], pc = {};
  (list || []).forEach(r => { if (names.length >= max) return; if (valid(r[0])) { names.push(r[0]); pc[r[0]] = pct(r[1]); } else skipped[kind].add(r[0]); });
  return { names, pc };
}

(async () => {
  const list = await get('');
  const all = [];
  list.pokemon_names.forEach(([n, u], i) => { const d = dexName(n); if (d) all.push({ n: d, api: n, u: pct(u), r: all.length + 1 }); else skipped.pokemon.add(n); });
  const tdata = {}; all.forEach(p => { tdata[p.n] = { u: p.u, r: p.r }; });
  const meta = [];
  for (const p of all.slice(0, TOP)) {
    process.stderr.write(`${p.r}/${Math.min(TOP, all.length)} ${p.n}\n`);
    const j = await get(p.api);
    const ab = pick(j.abilities_list, a => ABL.has(a), 'ability', 3), it = pick(j.items_list, i => ITL.has(i), 'item', 6), mv = pick(j.moves_list, m => !!MV[m], 'move', 12);
    const na = (j.natures_list || []).filter(x => NAT[x[0]]).slice(0, 4).map(x => [x[0], pct(x[1])]);
    const e = { n: p.n, u: p.u, ab: ab.names, it: it.names, mv: mv.names };
    if (na.length) e.na = na;
    e.pc = { ab: ab.pc, it: it.pc, mv: mv.pc };
    meta.push(e);
  }
  const info = { date: new Date().toISOString().slice(0, 10), teams: list.total_teams, tournaments: list.tournament_count, days: list.window_days, minPlayers: +list.min_players, format: list.selected_format_name, source: 'MunchStats (online Limitless tournaments)' };
  const out = `/* Tournament data, Pokémon Champions VGC, ${info.format}. GENERATED by tools/update-meta.js on ${info.date}: do not edit by hand.
   Source: MunchStats (data from Limitless TCG), online tournaments with ${info.minPlayers}+ players, last ${info.days} days, ${info.teams} teams. Usage = share of teams. */
var TMETA=${JSON.stringify(info)};
var TDATA=${JSON.stringify(tdata)};
var META=${JSON.stringify(meta)};
`;
  fs.writeFileSync(OUT, out);
  console.log(`wrote ${OUT}: ${all.length} Pokémon with usage, ${meta.length} with sets, ${info.teams} teams, ${info.date}`);
  Object.keys(skipped).forEach(k => { if (skipped[k].size) console.log(`dropped ${k} not in the app's data: ${[...skipped[k]].join(', ')}`); });
})().catch(e => { console.error('update-meta failed:', e.message); process.exit(1); });
